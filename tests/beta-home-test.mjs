import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const html=await readFile(new URL('../index.html',import.meta.url),'utf8');
const css=await readFile(new URL('../beta-home.css',import.meta.url),'utf8');
const must=(s,n,m)=>assert.ok(s.includes(n),`${m}: ${n}`);
for(const id of ['id="betaForm"','id="email"','id="consent"','id="betaSubmit"','id="formNote"','id="accountLink"','id="mobileAccountLink"'])must(html,id,'required landing behavior id missing');
for(const section of ['id="collect"','id="trade"','id="battle"','id="vision"','id="beta"'])must(html,section,'beta homepage section missing');
must(html,'COLLECT.</span><span>TRADE.</span>','primary platform hero missing');
must(html,'src="v-logo.svg"','original V logo must be used');
must(html,"/rest/v1/beta_waitlist",'beta waitlist endpoint missing');
must(html,"source:'landingpage'",'waitlist source marker missing');
must(html,"a.href=on?'app.html':'login.html'",'login/account routing missing');
must(html,'duelvanta-beta.css?v=1','shared design system not wired');
must(html,'beta-home.css?v=1','homepage skin not wired');
assert.equal((html.match(/createClient\(/g)||[]).length,1,'landing page must keep exactly one Supabase Auth client');
assert.ok(!html.includes('scanner-v16-'),'beta UI branch landing must not load Scanner V16 modules');
assert.ok(!html.includes('service_role')&&!css.includes('service_role'),'frontend must not contain service role');
assert.ok(!html.includes('<svg'),'landing must not redraw the fixed V logo inline');
must(css,'.home-hero','homepage hero styling missing');
must(css,'.world-card','platform world cards missing');
must(css,'.spotlight-grid','feature spotlight system missing');
must(css,'.home-mobile-nav','mobile landing navigation missing');
console.log('PASS: DUELVANTA beta homepage branding, auth, waitlist and scanner isolation');
