import assert from 'node:assert/strict';
await import('../scanner-v16-camera.js');
const c=globalThis.DV_SCAN_V16_CAMERA;
assert.ok(c,'camera safety module missing');
assert.equal(c.version,'16.7.0-lab');
assert.equal(c.frameReady({videoWidth:1920,videoHeight:1080,readyState:2}),true);
assert.equal(c.frameReady({videoWidth:0,videoHeight:0,readyState:4}),false);
assert.equal(c.streamLive({srcObject:{getVideoTracks:()=>[{readyState:'live',enabled:true}]}}),true);
assert.equal(c.streamLive({srcObject:{getVideoTracks:()=>[{readyState:'ended',enabled:true}]}}),false);
assert.equal(c.statePolicy('ready').captureDisabled,false);
assert.equal(c.statePolicy('starting').captureDisabled,true);
assert.equal(c.statePolicy('starting').startDisabled,true);
assert.equal(c.statePolicy('idle').startDisabled,false);
console.log('PASS: Scanner V16.7 iOS-safe camera readiness and non-blocking control policy');
