  assert.deepEqual(release,[{game_key:'magic',provider_key:'scryfall',provider_version:'1',state:'foundation',schema_phase:'persistence',snapshot_id:null}]);
  report.phases.M4={...await metadata(db),release,inventory_counts:states.map(s=>s.map(x=>x.length))};
  await db.exec(await read('database/tcg-i3-magic-on-demand-v1.sql'));
  const q6=await m6Queries(),h6=await m6Helper();
  await db.exec('savepoint author_m6');await db.exec(h6);
  const expected6=await inventories(db,q6),b6=await bootstrap(db,guardNames[1]);await db.exec('rollback to author_m6');
  files[OUTPUTS[2]]=header+'-- Completes the open common M6 delta; never activates beta.\n'+h6+roots.map((n,i)=>bridge(n,revisions[i],i,6,b6,[expected6])).join('')+'commit;\n';
  await db.exec(files[OUTPUTS[2]]);
