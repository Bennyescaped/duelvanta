  report.phases.M6={...await metadata(db,true),beta,capabilities,inventory_counts:expected6.map(x=>x.length)};
  for(const [p,s] of Object.entries(files)){
   assert.doesNotMatch(s,/\b(?:create|alter|drop)\s+(?:table|index|trigger|policy|schema)\b/i,'no product DDL: '+p);
   assert.ok(!s.includes(db.name));
  }
